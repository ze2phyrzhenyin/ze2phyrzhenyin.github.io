import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../public/francophone-sport-careers/', import.meta.url);
const locales = ['fr', 'en', 'zh'];
const resources = Object.fromEntries(await Promise.all(locales.map(async locale => [
  locale, JSON.parse(await readFile(new URL(`locales/${locale}.json`, root), 'utf8')),
])));

function leaves(value, path = '') {
  if (typeof value === 'string') return [[path, value]];
  return Object.entries(value).flatMap(([key, child]) => leaves(child, path ? `${path}.${key}` : key));
}
const reference = leaves(resources.fr);
for (const locale of locales) {
  const entries = leaves(resources[locale]);
  const actual = new Map(entries);
  if (JSON.stringify([...actual.keys()].sort()) !== JSON.stringify(reference.map(([key]) => key).sort())) {
    throw new Error(`Locale key parity failed: ${locale}`);
  }
  for (const [key, value] of reference) {
    const params = text => [...text.matchAll(/\{\{\s*(\w+)\s*\}\}/g)].map(match => match[1]).sort().join(',');
    if (params(value) !== params(actual.get(key))) throw new Error(`Placeholder mismatch: ${locale}:${key}`);
    if (locale !== 'zh' && /[\u3400-\u9fff]/u.test(actual.get(key))) throw new Error(`Untranslated Chinese: ${locale}:${key}`);
  }
}
const json = JSON.stringify(resources).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const output = new URL('locales/resources.js', root);
await writeFile(output, `/* Generated by scripts/build-sport-locales.mjs; edit fr/en/zh.json. */\nwindow.SPORT_LOCALES = ${json};\n`);
console.log(`Validated ${reference.length} translation entries per locale; wrote ${fileURLToPath(output)}.`);
