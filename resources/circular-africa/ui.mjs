export function formatDate(iso, locale, withTime = false) {
  const d = new Date(iso);
  const parts = Object.fromEntries(new Intl.DateTimeFormat('en-GB', { timeZone: 'Europe/Paris', year: 'numeric', month: 'numeric', day: 'numeric', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).formatToParts(d).map(p => [p.type, p.value]));
  const time = `${parts.hour}:${parts.minute}`;
  if (locale === 'zh') return `${parts.year} 年 ${Number(parts.month)} 月 ${Number(parts.day)} 日${withTime ? ` ${time}（巴黎时间）` : ''}`;
  const m = months[locale][Number(parts.month) - 1];
  return `${Number(parts.day)} ${m} ${parts.year}${withTime ? `, ${time} ${locale === 'es' ? '(hora de París)' : 'Paris time'}` : ''}`;
}

